// Preserve the archived holder-only adapter when refreshing current market artifacts.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { templateHash } from '../dist/abi.js';
import { canonicalRegistryJson } from '../dist/token-profiles.js';
const root = new URL('../', import.meta.url);
const sha = value => createHash('sha256').update(value).digest('hex');
const raw = await readFile(new URL('artifacts/KCC20September2026.placeholder.json', root));
// Exact bytes from kaspa-covenants 53175f6f21faf9cbd8dd31c51b677ae2aacc5fcf.
if (sha(raw) !== '961e14663608026a8b8fc082f8494ca3a35d274db74674ac995ccd1f63878840') throw Error('Archived holder artifact provenance mismatch');
const artifact = JSON.parse(raw);
const registry = JSON.parse(await readFile(new URL('artifacts/token-profiles.json', root)));
const script = Uint8Array.from(artifact.script), layout = artifact.state_layout;
const profile = {
  id: 'kaspacom-kcc20-september2026-holder-v1',
  artifactKey: 'KCC20September2026.placeholder.json',
  artifactSha256: sha(raw), artifactCanonicalSha256: sha(canonicalRegistryJson(artifact)),
  scriptSha256: sha(script), scriptLength: script.length,
  templateHash: Buffer.from(templateHash(script.slice(0, layout.start), script.slice(layout.start + layout.len))).toString('hex'),
  stateLayout: layout,
  standardRevision: artifact.standards.kcc20.commit,
  transferEntrypoint: 'transfer', delegatorEntrypoint: 'transfer_delegator',
  transferTag: artifact.abi.find(e => e.name === 'transfer').dispatch_tag,
  delegatorTag: artifact.abi.find(e => e.name === 'transfer_delegator').dispatch_tag,
  ownerSchemes: artifact.program_information.owner_schemes,
  maxTokenInputs: artifact.program_information.max_token_inputs,
  maxTokenOutputs: artifact.program_information.max_token_outputs,
  operations: ['transfer'], minimumHolderAmount: 1,
  fungibility: 'single-holder-class', nativeExtensions: true,
};
registry.profiles = registry.profiles.filter(p => p.id !== profile.id);
registry.profiles.push(profile);
const json = JSON.stringify(registry, null, 2), digest = sha(canonicalRegistryJson(registry));
await writeFile(new URL('artifacts/token-profiles.json', root), json + '\n');
await writeFile(new URL('artifacts/token-profiles.sha256', root), digest + '\n');
await writeFile(new URL('src/token-profiles.generated.ts', root), '// Generated by scripts/sync-reviewed-artifacts.mjs and scripts/append-legacy-holder-profile.mjs. Do not edit.\nimport type { TokenProfileRegistry } from "./token-profiles.js";\nexport const BUNDLED_TOKEN_PROFILE_DIGEST = ' + JSON.stringify(digest) + ';\nexport const BUNDLED_TOKEN_PROFILES: TokenProfileRegistry = ' + json + ';\n');
